    /**
     * 闸门 1：Kraft 等式 {@code Σ 2^(30 - len[i]) == 2^30}。
     *
     * <p>这是前缀码长度集合完整且自洽的<b>充要</b>条件，任何一处码长抄错都不成立。</p>
     */
    @Test
    public void testKraftEquality() {
        long sum = 0;
        for (int len : RFC_LENGTHS) {
            sum += 1L << (30 - len);
        }
        assertEquals(1L << 30, sum, "Kraft 等式不成立 —— 码长表抄错了");
    }

    /**
     * 闸门 2：生产代码由码长推导出的码字必须与 RFC 原文逐个一致。
     */
    @Test
    public void testCanonicalConstructionMatchesRfc() {
        for (int sym = 0; sym < 257; sym++) {
            assertEquals(RFC_LENGTHS[sym], HuffmanTable.getCodeLength(sym),
                    "符号 " + sym + " 的码长与 RFC 不符");
            assertEquals(RFC_CODES[sym], HuffmanTable.getCode(sym),
                    "符号 " + sym + " 的码字与 RFC 不符");
        }
    }

    /**
     * 闸门 3：前缀无关 —— 任一码字都不能是另一个码字的前缀。
     */
    @Test
    public void testPrefixFree() {
        for (int i = 0; i < 257; i++) {
            for (int j = 0; j < 257; j++) {
                if (i == j) {
                    continue;
                }
                int li = RFC_LENGTHS[i];
                int lj = RFC_LENGTHS[j];
                if (li > lj) {
                    continue;
                }
                int prefix = RFC_CODES[j] >>> (lj - li);
                assertTrue(prefix != RFC_CODES[i],
                        "符号 " + i + " 的码字是符号 " + j + " 的前缀 —— 码表不合法");
            }
        }
    }

    /**
     * 闸门 4：14 个锚点逐个断言（码字 + 码长）。
     */
    @Test
    public void testAnchors() {
        assertEquals(0x1ff8,      HuffmanTable.getCode(0),   "sym 0");
        assertEquals(13,          HuffmanTable.getCodeLength(0), "sym 0 len");
        assertEquals(0x7fffd8,    HuffmanTable.getCode(1),   "sym 1");
        assertEquals(23,          HuffmanTable.getCodeLength(1), "sym 1 len");
        assertEquals(0x14,        HuffmanTable.getCode(32),  "' '");
        assertEquals(6,           HuffmanTable.getCodeLength(32), "' ' len");
        assertEquals(0x0,         HuffmanTable.getCode(48),  "'0'");
        assertEquals(5,           HuffmanTable.getCodeLength(48), "'0' len");
        assertEquals(0x1,         HuffmanTable.getCode(49),  "'1'");
        assertEquals(0x2,         HuffmanTable.getCode(50),  "'2'");
        assertEquals(0x3,         HuffmanTable.getCode(97),  "'a'");
        assertEquals(0x4,         HuffmanTable.getCode(99),  "'c'");
        assertEquals(0x5,         HuffmanTable.getCode(101), "'e'");
        assertEquals(0x6,         HuffmanTable.getCode(105), "'i'");
        assertEquals(0x7,         HuffmanTable.getCode(111), "'o'");
        assertEquals(0x8,         HuffmanTable.getCode(115), "'s'");
        assertEquals(0x9,         HuffmanTable.getCode(116), "'t'");
        assertEquals(0x3fffffff,  HuffmanTable.getCode(256), "EOS");
        assertEquals(30,          HuffmanTable.getCodeLength(256), "EOS len");
    }

    @Test
    public void testEncodeDecodeRoundTrip() {
        String[] samples = {
                "www.example.com",
                "no-cache",
                "private",
                "Mon, 21 Oct 2013 20:13:21 GMT",
                "https://www.example.com",
                "/index.html",
                "",
                "application/json",
                "\u00e4\u00f6\u00fc"
        };
        for (String s : samples) {
            byte[] raw = s.getBytes(StandardCharsets.ISO_8859_1);
            byte[] encoded = HuffmanTable.encode(raw, 0, raw.length);
            byte[] decoded = HuffmanTable.decode(encoded, 0, encoded.length);
            assertArrayEquals(raw, decoded, "Huffman round trip 失败: " + s);
        }
    }

    /**
     * 编码后的长度必须与逐位累加一致（padding 用 EOS 的前缀补齐）。
     */
    @Test
    public void testEncodedLengthMatchesEncode() {
        byte[] raw = "hello hpack".getBytes(StandardCharsets.ISO_8859_1);
        byte[] encoded = HuffmanTable.encode(raw, 0, raw.length);
        assertEquals(HuffmanTable.encodedLength(raw, 0, raw.length), encoded.length);
    }

    @Test
    public void testDecodeRejectsEosSymbol() {
        // EOS 的码字是 30 个 1，直接构造一串 1 会在解码时命中 EOS
        byte[] allOnes = new byte[]{(byte) 0xff, (byte) 0xff, (byte) 0xff, (byte) 0xff};
        assertThrows(RuntimeException.class, () -> HuffmanTable.decode(allOnes, 0, allOnes.length));
    }

    @Test
    public void testDecodeRejectsBadPadding() {
        // "a" 的码字是 5 位 00011，补一个非全 1 的 padding 应当报错
        byte[] bad = new byte[]{(byte) 0b00011000};
        assertThrows(RuntimeException.class, () -> HuffmanTable.decode(bad, 0, bad.length));
    }
